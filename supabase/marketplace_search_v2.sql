create extension if not exists unaccent with schema extensions;
create extension if not exists pg_trgm with schema extensions;

create table if not exists public.search_synonyms (
  id bigint generated by default as identity primary key,
  canonical_term text not null,
  synonym text not null,
  created_at timestamptz not null default now(),
  unique (canonical_term, synonym)
);

alter table public.search_synonyms enable row level security;

drop policy if exists "Public can read search synonyms" on public.search_synonyms;
create policy "Public can read search synonyms"
on public.search_synonyms
for select
to anon, authenticated
using (true);

drop policy if exists "Admins can manage search synonyms" on public.search_synonyms;
create policy "Admins can manage search synonyms"
on public.search_synonyms
for all
to authenticated
using (
  exists (
    select 1 from public.profiles
    where profiles.id = (select auth.uid())
      and profiles.role in ('admin', 'super_admin')
  )
)
with check (
  exists (
    select 1 from public.profiles
    where profiles.id = (select auth.uid())
      and profiles.role in ('admin', 'super_admin')
  )
);

grant select on public.search_synonyms to anon, authenticated;
grant insert, update, delete on public.search_synonyms to authenticated;

